import test from 'node:test';
import assert from 'node:assert/strict';
import {openStore} from '../store.js';
import {initialize,currencies,enrich} from '../features.js';
import {refreshRates,restoreCurrencies} from '../exchange.js';
test('account endpoint uses conversion_rates and keeps the key out of stored metadata',async()=>{
 const db=openStore(':memory:');initialize(db);const now=Date.now();
 let endpoint;
 const mock=async url=>{endpoint=url;return {ok:true,json:async()=>({result:'success',base_code:'USD',time_last_update_unix:Math.floor(now/1000),time_next_update_unix:Math.floor(now/1000)+86400,conversion_rates:{USD:1,UGX:3987.2945,KES:129,EUR:0.9,GBP:0.8,JPY:150}})};};
 assert.equal(await refreshRates(db,mock,now,'test-key'),true);assert.match(endpoint,/v6\/test-key\/latest\/USD$/);assert.equal(db.prepare("SELECT rate FROM rates WHERE currency='UGX'").get().rate,3987294500);
 assert.ok(!JSON.stringify(db.prepare('SELECT * FROM exchange_sync').get()).includes('test-key'));db.close();
});
test('automatic rates cache daily data, recover from outages, and reject corrupt responses',async()=>{
 const db=openStore(':memory:');initialize(db);initialize(db);
 const now=Date.now();let calls=0;
 const payload={result:'success',base_code:'USD',time_last_update_unix:Math.floor(now/1000),time_next_update_unix:Math.floor(now/1000)+86400,rates:{USD:1,UGX:3700,KES:129,EUR:0.9,GBP:0.8,JPY:150,CAD:1.4,LBP:1685077.186678}};
 const fetcher=async()=>{calls++;return {ok:true,json:async()=>payload};};
 db.prepare('INSERT INTO rates VALUES(?,?,?)').run('UGX',123,now);
 assert.equal(enrich(db,{id:'x'},{tasks:[],withdrawals:[]}).rates.length,1,'old manual rates are never shown as automatic');
 assert.equal(await refreshRates(db,fetcher,now),true);assert.equal(currencies.JPY,0);assert.equal(db.prepare("SELECT rate FROM rates WHERE currency='UGX'").get().rate,3700000000);
 assert.equal(await refreshRates(db,fetcher,now+3600000),false);assert.equal(calls,1);
 db.prepare('UPDATE exchange_sync SET next_check=0').run();
 assert.equal(await refreshRates(db,async()=>{throw Error('offline');},now+86400000),false);
 assert.equal(db.prepare("SELECT rate FROM rates WHERE currency='UGX'").get().rate,3700000000);assert.ok(db.prepare('SELECT last_error FROM exchange_sync').get().last_error);
 assert.equal(await refreshRates(db,fetcher,now+86400001),false,'outage backoff prevents repeated requests');
 db.prepare('UPDATE exchange_sync SET next_check=0').run();
 assert.equal(await refreshRates(db,async()=>({ok:true,json:async()=>({...payload,rates:{...payload.rates,UGX:-1}})}),now),false);
 assert.equal(db.prepare("SELECT rate FROM rates WHERE currency='UGX'").get().rate,3700000000,'bad response never replaces cache');
 db.prepare('UPDATE exchange_sync SET next_check=0').run();assert.equal(await refreshRates(db,fetcher,now),true);
 delete currencies.JPY;restoreCurrencies(db);assert.equal(currencies.JPY,0);db.close();
});
