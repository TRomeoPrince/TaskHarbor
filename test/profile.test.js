import test from 'node:test';
import assert from 'node:assert/strict';
import {openStore} from '../store.js';
import {initialize} from '../features.js';
import {hash,verify} from '../auth.js';
import {registerProfile,payoutFeed} from '../community.js';
import {profileRoute} from '../profile.js';
test('optional username masks email; password changes require reauthentication and revoke other sessions',()=>{
 const db=openStore(':memory:');initialize(db);const u={id:'worker',email:'private@example.test',role:'worker'};
 db.prepare('INSERT INTO users(id,email,password_hash,role) VALUES(?,?,?,?)').run(u.id,u.email,hash('OriginalPassword123'),u.role);registerProfile(db,u.id,'','');
 db.prepare("INSERT INTO withdrawals(id,user_id,amount,destination,status) VALUES('w','worker',12,'0781920398','paid')").run();
 assert.equal(payoutFeed(db)[0].username,'pxxxx@example.test');assert.ok(!JSON.stringify(payoutFeed(db)).includes(u.email));
 const route=(path,body={},method='POST')=>profileRoute(db,u,'/api/'+path,body,method,'current');
 route('profile',{username:'my_name',currency:'UGX'});assert.equal(payoutFeed(db)[0].username,'my_name');assert.equal(route('profile',{},'GET').preferredCurrency,'UGX');
 route('profile',{username:''});assert.equal(payoutFeed(db)[0].username,'pxxxx@example.test');
 for(const token of ['current','other'])db.prepare('INSERT INTO sessions VALUES(?,?,?)').run(token,u.id,Date.now()+60000);
 assert.throws(()=>route('password',{currentPassword:'wrong',newPassword:'UpdatedPassword123'}),/incorrect/);
 assert.throws(()=>route('password',{currentPassword:'OriginalPassword123',newPassword:'short'}));
 route('password',{currentPassword:'OriginalPassword123',newPassword:'UpdatedPassword123'});
 assert.equal(db.prepare('SELECT COUNT(*) n FROM sessions').get().n,1);assert.ok(db.prepare("SELECT token FROM sessions WHERE token='current'").get());assert.ok(verify('UpdatedPassword123',db.prepare('SELECT password_hash FROM users').get().password_hash));
 assert.throws(()=>route('profile',{username:'bad name'}));assert.throws(()=>route('profile',{currency:'INVALID'}));db.close();
});
