test('corrections preserve evidence, staged images require current step, held funds never fund withdrawals',()=>{
 const db=openStore(':memory:');initialize(db);
 const admin={id:'admin',role:'admin'},worker={id:'worker',role:'worker'};
 for(const u of [admin,worker])db.prepare('INSERT INTO users(id,email,password_hash,role) VALUES(?,?,?,?)').run(u.id,u.id+'@test','x',u.role);
 const call=(u,p,b)=>route(db,u,'/api/'+p,b,{method:'POST'},{});
 const snapshot=()=>enrich(db,worker,{tasks:db.prepare('SELECT * FROM tasks').all(),withdrawals:[]}).tasks[0];
 const png={data:'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/lZkAAAAASUVORK5CYII='};
 call(admin,'tasks',{title:'Staged review',description:'Instructions',rewardAmount:'0.12',steps:[{title:'First',instruction:'First instruction'},{title:'Second',instruction:'Second instruction',images:[png]}]});
 const task=db.prepare('SELECT id FROM tasks').get().id;claim(db,task,worker.id);
 const img=db.prepare('SELECT id FROM images').get().id;
 const getImage=()=>route(db,worker,'/api/images/'+img,{}, {method:'GET'},{setHeader(){},end(){}});
 assert.throws(getImage,/not yet available/);assert.equal(snapshot().images.length,0);
 call(worker,'submit',{taskId:task,content:'Original result'});assert.throws(getImage,/not yet available/);
 let steps=snapshot().steps;
 call(worker,'step',{taskId:task,id:steps[0].id,content:'First result'});assert.equal(getImage(),'sent');assert.equal(snapshot().images.length,1);
 call(worker,'step',{taskId:task,id:steps[1].id,content:'Second result'});
 const submission=db.prepare('SELECT id FROM submissions').get().id;
 call(admin,'correction',{taskId:task,stepId:steps[0].id,content:'Correct first step'});
 assert.equal(snapshot().steps[0].completed,0);assert.equal(snapshot().steps[1].completed,0);assert.throws(getImage,/not yet available/);
 assert.ok(snapshot().history.some(h=>h.content==='First result'));
 assert.throws(()=>call(admin,'review',{id:submission,decision:'approved',note:'Premature'}));
 call(worker,'step',{taskId:task,id:steps[0].id,content:'Corrected first'});call(worker,'step',{taskId:task,id:steps[1].id,content:'Repeated second'});
 call(admin,'correction',{taskId:task,content:'Correct initial submission'});
 assert.throws(()=>call(worker,'step',{taskId:task,id:steps[0].id,content:'Skip resubmit'}),/Resubmit/);
 call(worker,'resubmit',{taskId:task,content:'Corrected initial result'});
 assert.ok(snapshot().history.some(h=>h.content==='Original result'));
 call(worker,'step',{taskId:task,id:steps[0].id,content:'First again'});call(worker,'step',{taskId:task,id:steps[1].id,content:'Second again'});
 call(admin,'review',{id:submission,decision:'approved',note:'Upstream accepted for hold'});
 assert.equal(wallet(db,worker.id).held,12);assert.equal(wallet(db,worker.id).available,0);assert.equal(wallet(db,worker.id).pending,0);
 assert.throws(()=>call(worker,'quote',{currency:'USD',amount:'0.01'}),/Insufficient/);
 assert.throws(()=>call(admin,'moderation',{taskId:task,decision:'approved',note:'Early release'}),/Three-day/);
 assert.throws(()=>call(admin,'review',{id:submission,decision:'approved',note:'Duplicate hold'}),/already held/);
 call(admin,'moderation',{taskId:task,decision:'rejected',note:'Upstream denied'});
 assert.equal(wallet(db,worker.id).held,0);assert.equal(wallet(db,worker.id).available,0);assert.equal(db.prepare('SELECT COUNT(*) n FROM ledger').get().n,0);
 assert.throws(()=>call(admin,'moderation',{taskId:task,decision:'approved',note:'Try to pay denied task'}));
 db.close();
});
