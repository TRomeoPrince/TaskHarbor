test('quick publishing fixes template values and blocks repeat Gmail addresses',()=>{
 const db=openStore(':memory:');initialize(db);const admin={id:'a',role:'admin'},worker={id:'w',role:'worker'};
 for(const u of [admin,worker])db.prepare('INSERT INTO users(id,email,password_hash,role) VALUES(?,?,?,?)').run(u.id,u.id+'@test','x',u.role);
 const body={firstName:'Sample',email:'sample.user@gmail.com',password:' exact password ',rewardAmount:'9.00'};
 const call=(u,b)=>route(db,u,'/api/quick-task',b,{method:'POST'},{});
 assert.throws(()=>call(worker,body),/Admin access/);
 const created=call(admin,body);assert.equal(created.externalId,'gmail:sampleuser');
 const task=db.prepare('SELECT * FROM tasks').get();assert.equal(task.title,'CREATE GMAIL');assert.equal(task.reward,12);assert.match(task.description,/🔐 Be sure/);
 const values=JSON.parse(db.prepare('SELECT fields FROM task_details').get().fields);assert.equal(values[3].value,' exact password ');assert.equal(values[4].value,'19 May 2000');
 assert.equal(db.prepare("SELECT COUNT(*) n FROM images WHERE kind LIKE 'instruction:%'").get().n,4);
 assert.throws(()=>call(admin,body));assert.throws(()=>call(admin,{...body,email:'sampleuser+alias@gmail.com'}));assert.equal(db.prepare('SELECT COUNT(*) n FROM tasks').get().n,1);
 assert.throws(()=>quickTask({...body,email:'bad@example.com'}));db.close();
});
